#!/usr/bin/env python3
"""Regenerate original copy firmware (requires GNU arm-none-eabi binutils)."""
from pathlib import Path
import struct
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
for name, base, exports, array in (
    ('copy', 0x200, ('copy_start', 'fast_start', 'copy_return'), 'copyFirmware'),
    ('arithmetic', 0x600, ('divarm_start', 'div_start', 'sqrt_start', 'arithmetic_return'), 'arithmeticFirmware'),
):
    with tempfile.TemporaryDirectory() as directory:
        obj, binary = Path(directory) / (name + '.o'), Path(directory) / (name + '.bin')
        subprocess.run(['arm-none-eabi-as', '-o', str(obj), str(root / 'firmware' / (name + '.s'))], check=True)
        subprocess.run(['arm-none-eabi-objcopy', '-O', 'binary', '-j', '.text', str(obj), str(binary)], check=True)
        symbols = {symbol: int(address, 16) for address, _, symbol in
                   (line.split() for line in subprocess.check_output(['arm-none-eabi-nm', str(obj)], text=True).splitlines())}
        words = struct.unpack('<' + 'I' * (binary.stat().st_size // 4), binary.read_bytes())
        output = f'// Generated by tools/firmware.py from original firmware/{name}.s.\n#pragma once\n'
        for symbol in exports:
            output += f'inline constexpr uint32_t {symbol} = 0x{base + symbols[symbol]:x};\n'
        output += f'inline constexpr uint32_t {array}[] = {{\n'
        output += ''.join(f'    0x{word:08x},\n' for word in words) + '};\n'
        (root / 'src' / f'gba_{name}_firmware.hpp').write_text(output)
